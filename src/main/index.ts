// Ensure only one instance runs at a time
const gotLock = app.requestSingleInstanceLock();
const uninstallExit = process.argv.includes('--quit-for-uninstall');
if (!gotLock || uninstallExit) {
  app.quit();
}

let mainWindow: BrowserWindow | null = null;
let tray: Tray | null = null;
let isQuitting = false;
let quitPending = false;
let ipcOperations: { waitForIdle(timeoutMs?: number): Promise<boolean> } | undefined;
let updateSettings: ((updates: Partial<AppSettings>) => Promise<AppSettings>) | undefined;
let menuLanguage: AppSettings['language'] | undefined;
let launchAtLogin: boolean | undefined;

function showMainWindow(): void {
  if (!mainWindow || mainWindow.isDestroyed()) return;
  if (mainWindow.isMinimized()) mainWindow.restore();
  mainWindow.show();
  mainWindow.focus();
}

app.on('second-instance', (_event, argv) => {
  // The uninstaller uses the same flush-and-confirm path as File > Exit.
  if (argv.includes('--quit-for-uninstall')) app.quit();
  // The sign-in entry of an already running copy must not pop the window open.
  else if (!startedAtLogin(argv)) showMainWindow();
});

// Every window, including snip overlays, stays on the application's own pages.
app.on('web-contents-created', (_event, contents) => {
  guardNavigation(contents, (url) => shell.openExternal(url));
});

// The taskbar groups and pins windows by this identity. It must match `appId` in
// electron-builder.yml, which the installer's Start menu shortcut carries; development runs
// (electron.exe) use their own ID so they are never grouped with the installed app.
if (process.platform === 'win32') {
  app.setAppUserModelId(app.isPackaged ? 'com.openmathpix.app' : 'com.openmathpix.app.dev');
}

/** Icons generated by `npm run icons`; packaged builds copy them to the resources folder. */
function iconResource(name: string): string {
  return app.isPackaged
    ? path.join(process.resourcesPath, name)
    : path.join(__dirname, '../../build', name);
}

function getIconPath(): string {
  // Windows picks the matching size from the .ico for every display scale factor.
  return iconResource(process.platform === 'win32' ? 'icon.ico' : 'icon.png');
}

function createMainWindow(): BrowserWindow {
  const win = new BrowserWindow({
    width: 800,
    height: 600,
    minWidth: 480,
    minHeight: 400,
    show: false,
    icon: getIconPath(),
    webPreferences: {
      preload: path.join(__dirname, '../preload/index.js'),
      nodeIntegration: false,
      contextIsolation: true,
    },
  });

  if (process.env.ELECTRON_RENDERER_URL) {
    win.loadURL(process.env.ELECTRON_RENDERER_URL);
  } else {
    win.loadFile(path.join(__dirname, '../renderer/index.html'));
  }

  // Started at sign-in: stay in the notification area until the user opens the window.
  win.once('ready-to-show', () => {
    if (!startedAtLogin()) win.show();
  });
  attachTextContextMenu(win, () => getSettings().language);

  win.on(
    'close',
    createWindowCloseHandler({
      isQuitting: () => isQuitting,
      isDestroyed: () => win.isDestroyed(),
      hide: () => {
        win.hide();
        // The window vanishing could look like an exit: say once where the app went.
        if (takeFirstTrayHint()) showTrayHint();
      },
    }),
  );

  return win;
}

function showTrayHint(): void {
  const language = getSettings().language;
  showPopup({
    title: translate(language, 'OpenMathpix is still running'),
    body: translate(
      language,
      'Use the snip shortcut any time. To exit, right-click the tray icon and choose Exit.',
    ),
    hint: translate(language, 'Click to open OpenMathpix'),
    closeLabel: translate(language, 'Close'),
    kind: 'info',
    durationMs: 9000,
    language,
  });
}

function createTray(): void {
  // A 16 px bitmap is blurry when the system scales it to 20-32 px. The .ico holds artwork
  // drawn for each size; elsewhere Electron loads tray@2x.png next to tray.png on HiDPI.
  tray = new Tray(
    process.platform === 'win32'
      ? getIconPath()
      : nativeImage.createFromPath(iconResource('tray.png')),
  );
  tray.setToolTip('OpenMathpix');

  tray.on('click', showMainWindow);
}

function refreshNativeMenus(): void {
  const language = getSettings().language;
  const actions = {
    changeLanguage: (next: AppSettings['language']) => {
      // Native radio items toggle before their callback. Restore the saved value
      // until the settings transaction has succeeded, including on write failure.
      refreshNativeMenus();
      void updateSettings?.({ language: next }).catch(() => {
        refreshNativeMenus();
        const text = getNativeText(getSettings().language);
        if (!mainWindow || mainWindow.isDestroyed() || isQuitting) return;
        void dialog
          .showMessageBox(mainWindow, {
            type: 'error',
            title: 'OpenMathpix',
            message: text.languageFailed,
            detail: text.languageFailedDetail,
          })
          .catch(() => {});
      });
    },
    snip: triggerSnip,
    open: showMainWindow,
    settings: () => {
      showMainWindow();
      mainWindow?.webContents.send(IPC.NAVIGATE, 'settings');
    },
    result: () => {
      showMainWindow();
      mainWindow?.webContents.send(IPC.NAVIGATE, 'result');
    },
    history: () => {
      showMainWindow();
      mainWindow?.webContents.send(IPC.NAVIGATE, 'history');
    },
    pasteImage: () => {
      if (quitPending) return;
      showMainWindow();
      mainWindow?.webContents.send(IPC.PASTE_IMAGE_REQUEST);
    },
    copyResult: () => {
      mainWindow?.webContents.send(IPC.COPY_RESULT_REQUEST);
    },
    about: () => {
      showMainWindow();
      if (mainWindow) {
        showAboutWindow(mainWindow, getSettings().language, iconResource('icon.png'));
      }
    },
    checkUpdates: () => {
      showMainWindow();
      if (mainWindow) void checkForUpdates(mainWindow, getSettings().language).catch(console.warn);
    },
    openGuide: () => {
      void shell.openExternal(userGuideUrl(getSettings().language)).catch(() => undefined);
    },
    reportIssue: () => {
      const url = issueUrl({
        version: app.getVersion(),
        os: `${os.type() === 'Windows_NT' ? 'Windows' : os.type()} ${os.release()}`,
        arch: process.arch,
      });
      void shell.openExternal(url).catch(() => undefined);
    },
    quit: () => app.quit(),
  };
  Menu.setApplicationMenu(
    Menu.buildFromTemplate(createApplicationMenuTemplate(language, process.platform, actions)),
  );
  tray?.setContextMenu(Menu.buildFromTemplate(createTrayMenuTemplate(language, actions)));
  menuLanguage = language;
}

function snip(): Promise<void> {
  if (!mainWindow || quitPending || isQuitting) return Promise.resolve();
  // Load the model while the user selects a region; the first recognition is then faster.
  void warmMfr().catch(() => undefined);
  return startSnip(mainWindow, { afterSnip: () => getSettings().afterSnip });
}

function triggerSnip(): void {
  void snip();
}

function registerGlobalShortcut(): void {
  const settings = getSettings();
  try {
    if (!globalShortcut.register(settings.snipHotkey, triggerSnip)) {
      // Reported in the window: see hotkeyStatus().
      console.warn('Snip hotkey unavailable:', settings.snipHotkey);
    }
  } catch (error) {
    console.warn('Could not register snip hotkey:', error);
  }
}

let hotkeySuspended = false;

/**
 * Settings records a new hotkey from key presses. Pressing the current hotkey there must
 * reach the recorder instead of starting a snip, so it is unregistered while recording.
 */
function suspendHotkey(suspended: boolean): void {
  hotkeySuspended = suspended;
  const accelerator = getSettings().snipHotkey;
  if (suspended) globalShortcut.unregister(accelerator);
  else if (!globalShortcut.isRegistered(accelerator)) registerGlobalShortcut();
}

/** The registration itself is the source of truth; another application may own the hotkey. */
function hotkeyStatus(retry: boolean): HotkeyStatus {
  const accelerator = getSettings().snipHotkey;
  if (retry && !globalShortcut.isRegistered(accelerator)) registerGlobalShortcut();
  return { accelerator, registered: globalShortcut.isRegistered(accelerator) };
}

function applyTheme(): void {
  const settings = getSettings();
  if (settings.theme === 'system') {
    nativeTheme.themeSource = 'system';
  } else {
    nativeTheme.themeSource = settings.theme;
  }
}

app.whenReady().then(async () => {
  // `ready` still fires in a second instance that is quitting. It must not open windows,
  // a tray icon or the model, nor write to the running instance's profile.
  if (!gotLock || uninstallExit) return;
  const initialSettings = getSettings();
  await adoptLegacyManagedDownloads(app.getPath('userData'), {
    downloadRoot: initialSettings.mfrDownloadDirectory || undefined,
    modelPath: initialSettings.mfrModelPath || undefined,
    textellerDownloadRoot: initialSettings.textellerDownloadDirectory || undefined,
    textellerModelPath: initialSettings.textellerModelPath || undefined,
  }).catch((error) => console.warn('Could not register existing model downloads:', error));
  initDb();
  launchAtLogin = initialSettings.launchAtLogin;
  try {
    syncLaunchAtLogin(launchAtLogin);
  } catch (error) {
    console.warn('Could not register OpenMathpix to start at sign-in:', error);
  }
  mainWindow = createMainWindow();
  const settingsService = createSettingsService({
    read: getSettings,
    assertModelDirectory: (directory) => {
      if (app.isPackaged)
        assertModelOutsideInstallation(directory, path.dirname(app.getPath('exe')));
    },
    persist: (input, verifiedEngine) => {
      const updates = validateSettingsUpdates(input);
      const previous = getSettings();
      const previousTheme = nativeTheme.themeSource;
      try {
        if (updates.theme !== undefined) nativeTheme.themeSource = updates.theme;
        if (updates.snipHotkey !== undefined) {
          saveWithShortcut(
            previous.snipHotkey,
            updates.snipHotkey,
            globalShortcut,
            triggerSnip,
            () => setSettings(updates, verifiedEngine),
          );
        } else {
          // An unavailable startup shortcut must not block unrelated settings changes.
          setSettings(updates, verifiedEngine);
        }
      } catch (error) {
        nativeTheme.themeSource = previousTheme;
        throw error;
      }
    },
    prepareModel: prepareMfrModel,
    prepareClearModel: prepareClearMfrModel,
    prepareTextellerModel: localModels.texteller.prepare,
    prepareClearTextellerModel: localModels.texteller.prepareClear,
    testCloud: testConnection,
    validationStarted: (settings) => cloudEngineStatus(settings, { state: 'checking' }),
    validationFailed: (settings, error) =>
      cloudEngineStatus(settings, {
        state: 'error',
        error: error instanceof Error ? error.message : 'Connection failed',
      }),
    changed: (settings) => {
      void broadcastEngineStatuses();
      // Free the previous engine's model as soon as another engine is in use.
      releaseUnusedModels(settings.ocrEngine);
      if (settings.launchAtLogin !== launchAtLogin) {
        launchAtLogin = settings.launchAtLogin;
        try {
          setLaunchAtLogin(launchAtLogin);
        } catch (error) {
          console.warn('Could not change the sign-in entry:', error);
        }
      }
      if (settings.language !== menuLanguage) {
        try {
          refreshNativeMenus();
        } catch (error) {
          // The saved setting remains authoritative if menus disappear during shutdown.
          console.warn('Could not refresh application menus:', error);
        }
      }
      for (const win of BrowserWindow.getAllWindows()) {
        try {
          if (!win.isDestroyed()) win.webContents.send(IPC.SETTINGS_CHANGED, settings);
        } catch {
          // A closing renderer must not turn a successful commit into a failed update.
        }
      }
    },
  });
  updateSettings = settingsService.update;
  ipcOperations = registerIpcHandlers(
    mainWindow,
    settingsService.update,
    settingsService.clearModel,
    {
      snip,
      showMainWindow,
      hotkeyStatus,
      suspendHotkey,
      isQuitting: () => quitPending || isQuitting,
      connectEngine: async (updates) => {
        const settings = await settingsService.connect(updates);
        cloudEngineStatus(settings, { state: 'ready' });
        return settings;
      },
    },
  );
  // Recording stops when the window loses focus; never leave the hotkey switched off,
  // even if the page could not report it (e.g. the renderer was reloaded or crashed).
  const resumeHotkey = () => {
    if (hotkeySuspended) suspendHotkey(false);
  };
  mainWindow.on('blur', resumeHotkey);
  mainWindow.webContents.on('did-start-navigation', resumeHotkey);
  mainWindow.webContents.on('render-process-gone', resumeHotkey);
  createTray();
  refreshNativeMenus();
  registerGlobalShortcut();
  applyTheme();
  // Restore a downloaded/selected local model without forcing first-time users to download.
  // Reapplying the already saved local engine performs strict model validation.
  const selectedEngine = getSettings().ocrEngine;
  if (selectedEngine !== 'paddleocr')
    void localModels[selectedEngine]
      .getStatus()
      .then((status) => {
        if (getSettings().ocrEngine === selectedEngine && status.state === 'ready') {
          return settingsService.update({ ocrEngine: selectedEngine });
        }
      })
      .catch(() => {
        // Model status carries a user-facing error; keep the saved configuration for repair.
      });
});

app.on('window-all-closed', () => {
  // Keep running in tray on all platforms
});

app.on('activate', showMainWindow);

app.on('will-quit', () => {
  globalShortcut.unregisterAll();
  disposeMfr();
  // A downloaded update the user chose to install starts once everything is saved.
  runPendingInstaller();
  tray?.destroy();
  tray = null;
});

app.on('before-quit', (event) => {
  if (isQuitting || !gotLock || !mainWindow || mainWindow.isDestroyed()) return;
  event.preventDefault();
  if (quitPending) return;
  quitPending = true;
  const window = mainWindow;
  void (async () => {
    try {
      const results = await Promise.all([
        flushBeforeQuit(window),
        ipcOperations?.waitForIdle(12_000) ?? Promise.resolve(true),
      ]);
      const saved = results.every(Boolean);
      if (!saved) {
        showMainWindow();
        const chinese = getSettings().language === 'zh-CN';
        const { response } = await dialog.showMessageBox(window, {
          type: 'warning',
          title: 'OpenMathpix',
          message: chinese
            ? '仍有未保存的更改或未完成的操作。'
            : 'Some changes or operations are still pending.',
          detail: chinese
            ? '返回应用以完成识别或修复保存错误。强制退出可能丢失尚未保存的内容。'
            : 'Return to finish recognition or resolve save errors. Exiting now may lose unsaved changes.',
          buttons: chinese ? ['返回应用', '仍然退出'] : ['Return to App', 'Exit Anyway'],
          defaultId: 0,
          cancelId: 0,
          noLink: true,
        });
        if (response !== 1) return;
      }
      isQuitting = true;
      disposeMfr();
      tray?.destroy();
      tray = null;
      app.quit();
    } catch (error) {
      console.warn('Could not finish application shutdown:', error);
      showMainWindow();
    } finally {
      quitPending = false;
    }
  })();
});
